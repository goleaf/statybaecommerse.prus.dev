#!/usr/bin/env node
/**
 * Regenerate the legacy `.husky/_/husky.sh` wrapper so older hook scripts keep working.
 * Husky v9 writes an informational stub during installation; we replace it with a shim that calls `_/h`.
 */
import { chmod, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const repoRoot = dirname(here);
const shimPath = join(repoRoot, '.husky', '_', 'husky.sh');
const shimContents = `#!/usr/bin/env sh\n# Compatibility shim generated by scripts/ensure-husky-shim.mjs.\n# It simply forwards to the maintained Husky helper in '_/h' so legacy hooks keep running.\n. \"$(dirname -- \"$0\")/h\"\n`;

await writeFile(shimPath, shimContents, 'utf8');
await chmod(shimPath, 0o755);
